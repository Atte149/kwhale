# ───────────────────────── helpers ─────────────────────────


def _docker_needs_sudo() -> bool:
    """Detect if docker commands require sudo on this host."""
    r = subprocess.run(["docker", "info"], capture_output=True)
    return r.returncode != 0


SUDO: list[str] = ["sudo"] if _docker_needs_sudo() else []


def run(cmd: list[str], cwd: Path | None = None, check: bool = True, capture: bool = False) -> subprocess.CompletedProcess:
    """Run a command, streaming output unless capture=True. Auto-prefixes sudo for docker."""
    # Auto-add sudo for docker commands if needed
    if cmd and cmd[0] == "docker" and SUDO:
        cmd = SUDO + cmd
    if capture:
        return subprocess.run(cmd, cwd=cwd, check=check, capture_output=True, text=True)
    return subprocess.run(cmd, cwd=cwd, check=check, text=True)


def prompt(msg: str, default: str = "", password: bool = False) -> str:
    """Interactive prompt with default fallback."""
    if password:
        import getpass
        val = getpass.getpass(f"{msg} [{'*' * len(default) if default else ''}]: ")
    else:
        suffix = f" [{default}]" if default else ""
        val = input(f"{msg}{suffix}: ").strip()
    return val or default


def confirm(msg: str, default: bool = True) -> bool:
    hint = "Y/n" if default else "y/N"
    val = input(f"{msg} [{hint}]: ").strip().lower()
    if not val:
        return default
    return val in ("y", "yes", "1", "true")


def header(text: str) -> None:
    print(f"\n{'=' * 60}\n  {text}\n{'=' * 60}")


def info(msg: str) -> None:
    print(f"  [+] {msg}")


def warn(msg: str) -> None:
    print(f"  [!] {msg}")


def err(msg: str) -> None:
    print(f"  [x] {msg}", file=sys.stderr)


def http_get(url: str, timeout: int = 10) -> int:
    try:
        req = urllib.request.Request(url, method="GET")
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            return resp.status
    except urllib.error.HTTPError as e:
        return e.code
    except Exception:
        return 0


def http_post_json(url: str, data: dict, timeout: int = 10) -> dict | None:
    try:
        body = json.dumps(data).encode()
        req = urllib.request.Request(
            url, data=body, headers={"Content-Type": "application/json"}, method="POST"
        )
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            return json.loads(resp.read())
    except Exception:
        return None


# ───────────────────────── env generation ─────────────────────────


def gen_password(length: int = 24) -> str:
    return secrets.token_urlsafe(length)[:length]


def gen_jwt_secret() -> str:
    return secrets.token_hex(32)


def write_env(path: Path, lines: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")
    info(f"Wrote {path}")


