# ───────────────────────── docker checks ─────────────────────────


def check_prerequisites() -> None:
    header("Checking prerequisites")
    for tool in ("docker", "git", "python3"):
        if not shutil.which(tool):
            err(f"'{tool}' not found. Please install it first.")
            sys.exit(1)
        info(f"{tool} found")

    # Check docker compose (v2 plugin or standalone)
    try:
        run(["docker", "compose", "version"], check=True, capture=True)
        info("docker compose v2 available")
    except (subprocess.CalledProcessError, FileNotFoundError):
        if shutil.which("docker-compose"):
            warn("Using standalone docker-compose (v1). Consider upgrading to v2.")
        else:
            err("docker compose not found. Install Docker Compose v2.")
            sys.exit(1)

    # Check docker daemon
    try:
        run(["docker", "info"], check=True, capture=True)
        info("Docker daemon running")
    except subprocess.CalledProcessError:
        err("Docker daemon not running. Start it: sudo systemctl start docker")
        sys.exit(1)


def ensure_networks() -> None:
    """Create external networks if they don't exist."""
    header("Ensuring external Docker networks")
    for net in EXTERNAL_NETWORKS:
        try:
            result = run(["docker", "network", "inspect", net], check=False, capture=True)
            if result.returncode == 0:
                info(f"Network '{net}' exists")
            else:
                run(["docker", "network", "create", net])
                info(f"Created network '{net}'")
        except Exception as e:
            warn(f"Could not ensure network '{net}': {e}")


# ───────────────────────── health checks ─────────────────────────


def wait_for_health(install_dir: Path, cfg: dict, timeout: int = 180) -> bool:
    header("Waiting for services to become healthy")
    api_port = cfg["api_port"]
    nav_port = cfg["navidrome_port"]
    api_url = f"http://127.0.0.1:{api_port}/healthz"
    nav_url = f"http://127.0.0.1:{nav_port}/rest/ping.view"

    deadline = time.time() + timeout
    services = {"API": api_url, "Navidrome": nav_url}
    status = {name: False for name in services}

    while time.time() < deadline:
        for name, url in services.items():
            if not status[name]:
                code = http_get(url, timeout=5)
                if code == 200:
                    info(f"{name} healthy (HTTP 200)")
                    status[name] = True
        if all(status.values()):
            return True
        time.sleep(3)

    for name, ok_ in status.items():
        if not ok_:
            err(f"{name} did not become healthy in {timeout}s")
    return False


