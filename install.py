"""KWhale one-command installer.

Usage:
    curl -fsSL https://raw.githubusercontent.com/Atte149/kwhale/main/install.py | python3 -
    python3 install.py [--non-interactive] [--data-root PATH] [--repo URL] [--branch BRANCH]

Clones the KWhale server repo, generates all .env files consistently, creates
data directories and external Docker networks, builds and starts the stack,
waits for healthchecks, and prints the API token + next steps.
"""

