def interactive_config(args: argparse.Namespace) -> dict:
    header("KWhale Installer — Configuration")

    install_dir = Path(args.install_dir or Path.cwd() / INSTALL_DIR_NAME).resolve()
    data_root = Path(args.data_root or (install_dir.parent / "kwhale-data")).resolve()

    cfg = {
        "install_dir": install_dir,
        "data_root": str(data_root),
        "repo_url": args.repo or DEFAULT_REPO,
        "branch": args.branch or DEFAULT_BRANCH,
        "api_port": args.api_port or 19000,
        "navidrome_port": args.navidrome_port or 4535,
    }

    if args.non_interactive:
        cfg.update({
            "navidrome_username": "admin",
            "navidrome_password": gen_password(),
            "postgres_password": gen_password(),
            "jwt_secret": gen_jwt_secret(),
            "openai_api_base": "https://api.openai.com/v1",
            "openai_api_key": "",
            "embed_model": "text-embedding-3-small",
            "llm_model": "gpt-4o-mini",
            "omni_model": "",
            "icm_partner_key": "",
            "yandex_token": "",
        })
        return cfg

    cfg["navidrome_username"] = prompt("Navidrome admin username", "admin")
    cfg["navidrome_password"] = prompt("Navidrome admin password", gen_password(16), password=True)
    cfg["postgres_password"] = prompt("PostgreSQL password", gen_password(), password=True)
    cfg["jwt_secret"] = gen_jwt_secret()
    info(f"Generated JWT secret ({len(cfg['jwt_secret'])} chars)")

    print()
    print("  AI features need an OpenAI-compatible API (embeddings + LLM).")
    cfg["openai_api_base"] = prompt("OpenAI API base URL", "https://api.openai.com/v1")
    cfg["openai_api_key"] = prompt("OpenAI API key", "", password=True)
    cfg["embed_model"] = prompt("Embedding model", "text-embedding-3-small")
    cfg["llm_model"] = prompt("LLM Model", "gpt-4o-mini")

    print()
    print("  Optional: source plugins (leave blank to skip).")
    cfg["icm_partner_key"] = prompt("ICM Partner Key", "", password=True)
    cfg["yandex_token"] = prompt("Yandex Music Token", "", password=True)
    cfg["omni_model"] = ""

    return cfg


def clone_repo(cfg: dict) -> None:
    install_dir = cfg["install_dir"]
    header(f"Cloning KWhale from {cfg['repo_url']}")

    if install_dir.exists() and (install_dir / ".git").exists():
        info(f"Repo exists at {install_dir}, pulling latest...")
        run(["git", "fetch", "--all"], cwd=install_dir)
        run(["git", "checkout", cfg["branch"]], cwd=install_dir)
        run(["git", "pull", "origin", cfg["branch"]], cwd=install_dir)
    elif install_dir.exists() and any(install_dir.iterdir()):
        err(f"Directory {install_dir} exists and is not empty.")
        sys.exit(1)
    else:
        install_dir.parent.mkdir(parents=True, exist_ok=True)
        run(["git", "clone", "-b", cfg["branch"], cfg["repo_url"], str(install_dir)])
        info(f"Cloned to {install_dir}")


def create_data_dirs(cfg: dict) -> None:
    data_root = Path(cfg["data_root"])
    header(f"Creating data directories at {data_root}")
    for sub in ("music/library", "music/incoming", "music/failed", "navidrome", "postgres", "redis"):
        d = data_root / sub
        d.mkdir(parents=True, exist_ok=True)
    info(f"Data root: {data_root}")


def build_and_start(cfg: dict) -> None:
    install_dir = cfg["install_dir"]
    header("Building Docker images (this may take a while...)")

    # Use compose override to set custom ports if non-default
    if cfg["api_port"] != 19000 or cfg["navidrome_port"] != 4535:
        write_compose_override(install_dir, cfg)

    run(["docker", "compose", "build"], cwd=install_dir)
    info("Build complete")

    header("Starting services")
    run(["docker", "compose", "up", "-d"], cwd=install_dir)
    info("Services started")


def write_compose_override(install_dir: Path, cfg: dict) -> None:
    """Write docker-compose.override.yml for custom ports."""
    override = install_dir / "docker-compose.override.yml"
    lines = [
        "services:",
        "  navidrome:",
        "    ports:",
        f'      - "127.0.0.1:{cfg["navidrome_port"]}:4533"',
        "  api:",
        "    ports:",
        f'      - "127.0.0.1:{cfg["api_port"]}:8000"',
        "  tagger:",
        "    ports:",
        f'      - "127.0.0.1:{cfg["api_port"] + 93}:8093"',
    ]
    write_env(override, lines)
    info(f"Wrote compose override for custom ports")


def get_api_token(cfg: dict) -> str | None:
    header("Getting API token")
    url = f"http://127.0.0.1:{cfg['api_port']}/api/auth/login"
    resp = http_post_json(url, {
        "username": cfg["navidrome_username"],
        "password": cfg["navidrome_password"],
    }, timeout=15)
    if resp and "token" in resp:
        info(f"Login successful, token length: {len(resp['token'])}")
        return resp["token"]
    warn("Could not get API token. You can log in manually later.")
    return None


def offer_first_scan(cfg: dict, token: str | None) -> None:
    if not token:
        return
    if cfg.get("non_interactive"):
        return
    if not confirm("Trigger first library index (audio analysis)?", default=False):
        return
    url = f"http://127.0.0.1:{cfg['api_port']}/api/vibe/index-all"
    req = urllib.request.Request(url, headers={"Authorization": f"Bearer {token}"}, method="POST")
    try:
        with urllib.request.urlopen(req, timeout=15) as resp:
            if resp.status == 202:
                info("Indexing started in background. Check: docker compose logs -f worker")
            else:
                warn(f"Index trigger returned {resp.status}")
    except Exception as e:
        warn(f"Could not trigger indexing: {e}")


def print_summary(cfg: dict, token: str | None) -> None:
    header("KWhale is running!")
    print(f"""
  Data root:     {cfg['data_root']}
  Install dir:   {cfg['install_dir']}

  Services:
    API:         http://127.0.0.1:{cfg['api_port']}
    API docs:    http://127.0.0.1:{cfg['api_port']}/docs
    Navidrome:   http://127.0.0.1:{cfg['navidrome_port']}

  Credentials:
    Navidrome:   {cfg['navidrome_username']} / (password you set)
    API token:   {token or '(login manually)'}

  Next steps:
    1. Add music: copy files to {cfg['data_root']}/music/library/
    2. Navidrome auto-scans every 1 minute
    3. Index: curl -X POST http://127.0.0.1:{cfg['api_port']}/api/vibe/index-all \\
         -H "Authorization: Bearer {token or 'TOKEN'}"
    4. Logs:   cd {cfg['install_dir']} && docker compose logs -f worker

  Management:
    python3 {cfg['install_dir'] / 'kwhalectl.py'} status
    python3 {cfg['install_dir'] / 'kwhalectl.py'} smoke
""")


# ───────────────────────── entrypoint ─────────────────────────


def main() -> None:
    parser = argparse.ArgumentParser(description="KWhale one-command installer")
    parser.add_argument("--non-interactive", action="store_true", help="Run without prompts (CI/automated)")
    parser.add_argument("--data-root", help="Data root path (default: ../kwhale-data)")
    parser.add_argument("--install-dir", help="Install directory (default: ./kwhale)")
    parser.add_argument("--repo", help="Git repo URL")
    parser.add_argument("--branch", help="Git branch")
    parser.add_argument("--api-port", type=int, help="API host port (default: 19000)")
    parser.add_argument("--navidrome-port", type=int, help="Navidrome host port (default: 4535)")
    args = parser.parse_args()

    print(r"""
  _  __  _  __   ____  _          __  __
 | |/ / | |/ /  |  _ \| |        |  \/  |
 | ' /  | ' /   | |_) | |        | \  / |
 | . \  | . \   |  _ <| |___     | |\/| |
 |_|\_\ |_|\_\  |_| \_\_____|    |_|  |_|
        Self-hosted music with AI recommendations
""")

    check_prerequisites()
    cfg = interactive_config(args)
    clone_repo(cfg)

    # Re-resolve install_dir in case it was relative
    install_dir = cfg["install_dir"]
    if not (install_dir / "docker-compose.yml").exists():
        err(f"docker-compose.yml not found in {install_dir}")
        sys.exit(1)

    ensure_networks()
    create_data_dirs(cfg)
    generate_env_files(install_dir, cfg)
    build_and_start(cfg)

    if not wait_for_health(install_dir, cfg, timeout=300):
        err("Some services did not become healthy. Check logs:")
        print(f"  cd {install_dir} && docker compose logs")
        sys.exit(1)

    token = get_api_token(cfg)
    offer_first_scan(cfg, token)
    print_summary(cfg, token)


if __name__ == "__main__":
    main()